'use strict';
/* Vulnora - client-side PDF reports (jsPDF + autotable, both vendored - works offline).
 * Branding (company name, logo, colours, footer) comes from /api/settings. */
(function () {
  const SEVS = ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW', 'UNKNOWN'];
  const RANK = { CRITICAL: 0, HIGH: 1, MEDIUM: 2, LOW: 3, UNKNOWN: 4 };
  const COL = { CRITICAL: [255, 61, 113], HIGH: [255, 138, 61], MEDIUM: [245, 197, 66], LOW: [56, 189, 248], UNKNOWN: [139, 147, 167] };
  const INK = [30, 34, 60], MUTED = [110, 116, 145];
  const MAX_ROWS = 800;
  const DEFAULT_BRAND = { company: '', preparedBy: '', reportTitle: 'Security Scan Report', footer: 'Confidential security report', headerColor: '#0e1126', logo: null, showTrivyLogo: true };

  // jsPDF's built-in fonts are Latin-1 only: replace anything else so text never garbles
  const clean = (s) => String(s == null ? '' : s).replace(/\u2192/g, '->').replace(/[\u2018\u2019]/g, "'").replace(/[\u201C\u201D]/g, '"').replace(/[\u2013\u2014]/g, '-').replace(/\u2026/g, '...').replace(/[^\x09\x0A\x0D\x20-\x7E\xA0-\xFF]/g, '?');
  const total = (c) => SEVS.reduce((n, s) => n + (c[s] || 0), 0);
  const hexRgb = (h) => { const m = /^#?([0-9a-f]{6})$/i.exec(h || ''); const n = parseInt(m ? m[1] : '0e1126', 16); return [n >> 16 & 255, n >> 8 & 255, n & 255]; };
  const isLight = (rgb) => (0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2]) > 160;

  // Vulnora mark: white-lettered version for dark headers, dark-lettered for light headers
  const logoCache = {};
  async function vulnoraLogo(dark) {
    if (window.__vulnoraLogo) return window.__vulnoraLogo(dark); // server-side rendering supplies its own images
    const f = dark ? 'logo-dark.png' : 'logo.png';
    if (logoCache[f]) return logoCache[f];
    try {
      const b = await (await fetch(f)).blob();
      logoCache[f] = await new Promise((res) => { const r = new FileReader(); r.onload = () => res(r.result); r.readAsDataURL(b); });
    } catch (e) { return null; }
    return logoCache[f];
  }
  async function getBrand() {
    try { const r = await fetch('/api/settings', { cache: 'no-store' }); if (r.ok) return { ...DEFAULT_BRAND, ...(await r.json()) }; } catch (e) { /* offline */ }
    return { ...DEFAULT_BRAND };
  }

  function stripe(doc, y, h, w, x0 = 0) { // 4-colour brand stripe taken from the logo palette
    const cs = [[34, 195, 245], [31, 111, 255], [79, 82, 250], [109, 61, 245]];
    const seg = w / cs.length;
    cs.forEach((c, i) => { doc.setFillColor(...c); doc.rect(x0 + i * seg, y, seg + 0.5, h, 'F'); });
  }

  /* Draws the branded cover band. Returns the y position below it. */
  async function cover(doc, brand, { title, target, metaLine }) {
    const W = doc.internal.pageSize.getWidth(), M = 40;
    const bg = hexRgb(brand.headerColor);
    const light = isLight(bg);
    const fg = light ? INK : [255, 255, 255];
    const sub = light ? [90, 96, 125] : [190, 196, 225];
    doc.setFillColor(...bg); doc.rect(0, 0, W, 150, 'F'); stripe(doc, 150, 5, W);

    // Logo: the company logo if set, otherwise the Trivy logo
    let x = M;
    const logoBox = { w: 130, h: 54 };
    let img = brand.logo, isCompany = !!brand.logo;
    if (!img && brand.showTrivyLogo !== false) img = await vulnoraLogo(light);
    if (img) {
      try {
        const p = doc.getImageProperties(img);
        const sc = isCompany ? Math.min(logoBox.w / p.width, logoBox.h / p.height) : 48 / p.height;
        const w = p.width * sc, h = p.height * sc;
        doc.addImage(img, img.startsWith('data:image/jpeg') ? 'JPEG' : 'PNG', M, 26 + (48 - Math.min(h, 54)) / 2, w, h, isCompany ? 'brandlogo' : 'vlogo' + (light ? 'd' : ''), 'FAST');
        x = M + w + 14;
      } catch (e) { /* bad image - skip it */ }
    }
    doc.setTextColor(...fg); doc.setFont('helvetica', 'bold'); doc.setFontSize(22);
    doc.text(clean(title || brand.reportTitle || DEFAULT_BRAND.reportTitle), x, 52);
    if (brand.company) {
      // company name: bold and prominent, date on its own line underneath
      doc.setFont('helvetica', 'bold'); doc.setFontSize(15); doc.setTextColor(...fg);
      doc.text(doc.splitTextToSize(clean(brand.company), W - x - M - 20)[0], x, 72);
      doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(...sub);
      doc.text('Generated ' + new Date().toLocaleString(), x, 86);
    } else {
      doc.setFont('helvetica', 'normal'); doc.setFontSize(10.5); doc.setTextColor(...sub);
      doc.text('Generated by Vulnora  |  ' + new Date().toLocaleString(), x, 70);
    }

    // small Vulnora mark top-right when a company logo is used
    if (isCompany && brand.showTrivyLogo !== false) {
      const t = await vulnoraLogo(light);
      if (t) { try { const p = doc.getImageProperties(t); const hh = 30, ww = p.width * hh / p.height; doc.addImage(t, 'PNG', W - M - ww, 22, ww, hh, 'vlogo' + (light ? 'd' : ''), 'FAST'); } catch (e) { /* ignore */ } }
    }

    doc.setFontSize(13); doc.setTextColor(...fg);
    doc.text(doc.splitTextToSize(clean(target), W - 2 * M).slice(0, 2), M, 114);
    doc.setFontSize(9.5); doc.setTextColor(...sub);
    const ml = metaLine + (brand.preparedBy ? '  |  Prepared by ' + brand.preparedBy : '');
    doc.text(doc.splitTextToSize(clean(ml), W - 2 * M)[0], M, 136);
    return 180;
  }

  function footers(doc, brand) {
    const W = doc.internal.pageSize.getWidth(), H = doc.internal.pageSize.getHeight(), M = 40;
    const left = [brand.company, brand.footer].filter(Boolean).join(' - ') || 'Vulnora - See Vulnerabilities. Secure Every Layer.';
    const n = doc.getNumberOfPages();
    for (let i = 1; i <= n; i++) {
      doc.setPage(i); doc.setFontSize(8); doc.setTextColor(...MUTED); doc.setFont('helvetica', 'normal');
      if (brand.company) {
        doc.setFont('helvetica', 'bold'); const c = clean(brand.company).slice(0, 60); doc.text(c, M, H - 18);
        if (brand.footer) { const cw = doc.getTextWidth(c); doc.setFont('helvetica', 'normal'); doc.text(' - ' + clean(brand.footer).slice(0, 60), M + cw, H - 18); }
      } else doc.text(clean(left).slice(0, 110), M, H - 18);
      doc.text(`Vulnora  |  Page ${i} of ${n}`, W - M, H - 18, { align: 'right' });
    }
  }
  const headStyles = (brand) => { const bg = hexRgb(brand.headerColor); return { fillColor: bg, textColor: isLight(bg) ? INK : 255, fontSize: 9 }; };
  const fileSafe = (s) => String(s).replace(/[^a-z0-9._-]+/gi, '_').slice(0, 40);
  const sevCellAt = (col) => (d) => { if (d.section === 'body' && d.column.index === col && COL[d.cell.raw]) { d.cell.styles.fillColor = COL[d.cell.raw]; d.cell.styles.textColor = [16, 18, 31]; d.cell.styles.fontStyle = 'bold'; } };

  /* ================= single-scan report ================= */
  // Builds the scan PDF and returns the jsPDF document (used by the browser download and by email alerts)
  window.createScanPdf = async function (scan, brandOverride) {
    const { jsPDF } = window.jspdf;
    const brand = brandOverride || await getBrand();
    const doc = new jsPDF({ unit: 'pt', format: 'a4' });
    const W = doc.internal.pageSize.getWidth(), H = doc.internal.pageSize.getHeight(), M = 40;
    const f = scan.findings, sm = scan.summary, meta = scan.meta || {};
    const HS = headStyles(brand);

    let y = await cover(doc, brand, {
      target: scan.target,
      metaLine: `${scan.module.toUpperCase()} scan  |  ${new Date(scan.createdAt).toLocaleString()}  |  ${(scan.durationMs / 1000).toFixed(1)}s`,
    });

    /* ---- executive summary (plain-English, from summary.js) ---- */
    const sumy = window.TrivySummary.summarize(scan);
    const RISKC = { Critical: COL.CRITICAL, High: COL.HIGH, Medium: COL.MEDIUM, Low: COL.LOW, None: [52, 211, 153] };
    doc.setTextColor(...INK); doc.setFont('helvetica', 'bold'); doc.setFontSize(14); doc.text('Executive summary', M, y);
    // risk badge on the right
    const rl = 'OVERALL RISK: ' + sumy.risk.toUpperCase();
    doc.setFontSize(9); const rw = doc.getTextWidth(rl) + 18;
    doc.setFillColor(...RISKC[sumy.risk]); doc.roundedRect(W - M - rw, y - 13, rw, 19, 4, 4, 'F');
    doc.setTextColor(16, 18, 31); doc.text(rl, W - M - rw + 9, y);
    y += 20;
    const para = (txt, x0, width, size, bold, color) => {
      doc.setFont('helvetica', bold ? 'bold' : 'normal'); doc.setFontSize(size); doc.setTextColor(...color);
      const ls = doc.splitTextToSize(clean(txt), width); doc.text(ls, x0, y); y += ls.length * (size + 3);
    };
    para(sumy.headline, M, W - 2 * M, 11, true, INK); y += 6;
    const block = (title, items, numbered) => {
      if (!items.length) return;
      if (y > H - 120) { doc.addPage(); y = M + 10; }
      doc.setFont('helvetica', 'bold'); doc.setFontSize(10.5); doc.setTextColor(...INK); doc.text(title, M, y); y += 14;
      items.forEach((t, i) => {
        if (y > H - 70) { doc.addPage(); y = M + 10; }
        doc.setFont('helvetica', 'bold'); doc.setFontSize(9.5); doc.setTextColor(...MUTED);
        doc.text(numbered ? `${i + 1}.` : '-', M + 4, y);
        para(t, M + 18, W - 2 * M - 18, 9.5, false, [60, 64, 90]); y += 3;
      });
      y += 6;
    };
    block('Key findings', sumy.points, false);
    block('Recommended actions (most urgent first)', sumy.actions, true);
    y += 4;
    if (y > H - 300) { doc.addPage(); y = M + 10; }

    /* ---- severity tiles ---- */
    const all = { CRITICAL: 0, HIGH: 0, MEDIUM: 0, LOW: 0, UNKNOWN: 0 };
    ['vulns', 'secrets', 'misconfigs', 'licenses'].forEach((k) => SEVS.forEach((s) => (all[s] += sm[k][s] || 0)));
    const tw = (W - 2 * M - 4 * 8) / 5;
    SEVS.forEach((s, i) => {
      const x = M + i * (tw + 8);
      doc.setFillColor(...COL[s]); doc.roundedRect(x, y, tw, 56, 6, 6, 'F');
      doc.setTextColor(16, 18, 31); doc.setFont('helvetica', 'bold'); doc.setFontSize(22); doc.text(String(all[s]), x + 12, y + 30);
      doc.setFontSize(8.5); doc.text(s, x + 12, y + 46);
    });
    y += 76;

    /* ---- stacked bar of total ---- */
    const t = total(all);
    if (t) {
      let x = M; const bw = W - 2 * M;
      SEVS.forEach((s) => { const w = (all[s] / t) * bw; if (w > 0) { doc.setFillColor(...COL[s]); doc.rect(x, y, w, 12, 'F'); x += w; } });
      doc.setFontSize(8.5); doc.setTextColor(...MUTED); doc.setFont('helvetica', 'normal');
      doc.text(`Share of ${t} total findings by severity`, M, y + 26); y += 40;
    }

    /* ---- scan details + summary table ---- */
    doc.autoTable({
      startY: y, margin: { left: M, right: M }, theme: 'grid',
      head: [['Category', ...SEVS.map((s) => s[0] + s.slice(1).toLowerCase()), 'Total']],
      body: [['Vulnerabilities', 'vulns'], ['Secrets', 'secrets'], ['Misconfigurations', 'misconfigs'], ['Licenses', 'licenses']].map(([n, k]) => [n, ...SEVS.map((s) => sm[k][s] || 0), total(sm[k])]),
      headStyles: HS, styles: { fontSize: 9.5, cellPadding: 5 },
      columnStyles: { 0: { fontStyle: 'bold' } }, alternateRowStyles: { fillColor: [246, 247, 252] },
    });
    y = doc.lastAutoTable.finalY + 18;
    const kv = [['Target', clean(scan.target)], ['Artifact type', clean(meta.artifactType || scan.source)], [scan.module === 'webapp' ? 'Web server' : 'Operating system', clean(meta.os || '-')], ['Scanners', clean((scan.scanners || []).join(', ') || '-')], ['Severity filter', clean((scan.severities || []).join(', '))], scan.module === 'webapp' ? ['Requests sent', String(meta.requests || '-')] : ['Packages analysed', String(meta.packages || '-')], ['Scan engine', clean(scan.engine)]];
    if (meta.imageId) kv.push(['Image ID', clean(meta.imageId)]);
    if (brand.company) kv.unshift(['Organisation', clean(brand.company)]);
    if (brand.preparedBy) kv.push(['Prepared by', clean(brand.preparedBy)]);
    doc.autoTable({ startY: y, margin: { left: M, right: M }, theme: 'plain', body: kv, styles: { fontSize: 9, cellPadding: 3, textColor: [60, 64, 90] }, columnStyles: { 0: { fontStyle: 'bold', cellWidth: 110, textColor: INK }, 1: { cellWidth: 'auto' } } });
    y = doc.lastAutoTable.finalY + 16;

    /* ---- top packages ---- */
    const pk = new Map();
    f.vulns.forEach((v) => { const o = pk.get(v.pkg) || { n: 0, w: 99, fix: 0 }; o.n++; o.w = Math.min(o.w, RANK[v.severity]); if (v.fixed) o.fix++; pk.set(v.pkg, o); });
    const top = [...pk.entries()].sort((a, b) => a[1].w - b[1].w || b[1].n - a[1].n).slice(0, 6);
    if (top.length) {
      if (y > H - 190) { doc.addPage(); y = M; }
      doc.setFont('helvetica', 'bold'); doc.setFontSize(13); doc.setTextColor(...INK); doc.text('Top affected packages', M, y);
      doc.autoTable({
        startY: y + 8, margin: { left: M, right: M }, theme: 'striped',
        head: [['Package', 'Vulns', 'Worst severity', 'Fixable']],
        body: top.map(([n, o]) => [clean(n), o.n, SEVS[o.w], o.fix]),
        headStyles: HS, styles: { fontSize: 9, cellPadding: 3 }, didParseCell: sevCellAt(2),
      });
    }

    /* ---- detail sections ---- */
    const section = (title, rows, head, map, widths) => {
      if (!rows.length) return;
      const sorted = rows.slice().sort((a, b) => RANK[a.severity] - RANK[b.severity]);
      const cut = sorted.slice(0, MAX_ROWS);
      doc.addPage();
      doc.setFont('helvetica', 'bold'); doc.setFontSize(15); doc.setTextColor(...INK); doc.text(`${title} (${rows.length})`, M, M + 6);
      stripe(doc, M + 12, 2.5, 90, M);
      if (rows.length > cut.length) { doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5); doc.setTextColor(...MUTED); doc.text(`Showing the ${cut.length} most severe of ${rows.length}. Export CSV/JSON from the dashboard for the full list.`, M, M + 28); }
      doc.autoTable({
        startY: M + 36, margin: { left: M, right: M, bottom: 36 }, theme: 'striped', head: [head], body: cut.map(map),
        headStyles: { ...HS, fontSize: 8.5 }, styles: { fontSize: 7.8, cellPadding: 3.5, overflow: 'linebreak', valign: 'top' },
        columnStyles: widths, didParseCell: sevCellAt(0), rowPageBreak: 'avoid',
      });
    };
    const vFix = f.vulns.filter((v) => v.fixed), vNo = f.vulns.filter((v) => !v.fixed);
    const vw = { 0: { cellWidth: 52 }, 1: { cellWidth: 74 }, 2: { cellWidth: 72 }, 3: { cellWidth: 70 }, 4: { cellWidth: 74 } };
    section('Vulnerabilities - fix available (upgrade these first)', vFix, ['Severity', 'CVE', 'Package', 'Installed', 'Upgrade to', 'Title'],
      (v) => [v.severity, clean(v.id), clean(v.pkg), clean(v.installed), clean(v.fixed), clean(v.title)], vw);
    section('Vulnerabilities - no fix available yet', vNo, ['Severity', 'CVE', 'Package', 'Installed', 'Title'],
      (v) => [v.severity, clean(v.id), clean(v.pkg), clean(v.installed), clean(v.title)], { 0: { cellWidth: 52 }, 1: { cellWidth: 74 }, 2: { cellWidth: 72 }, 3: { cellWidth: 80 } });
    section('Secrets', f.secrets, ['Severity', 'Rule', 'Title', 'File', 'Line'],
      (s) => [s.severity, clean(s.id), clean(s.title), clean(s.target), s.line || '-'], { 0: { cellWidth: 52 }, 4: { cellWidth: 36 } });
    if (scan.module === 'webapp') section('Web security findings', f.misconfigs, ['Severity', 'Finding', 'Evidence', 'CWE / OWASP', 'How to fix'],
      (m) => [m.severity, clean(m.title) + '\n' + clean(m.target), clean(m.message), clean(m.ruleId), clean(m.resolution)], { 0: { cellWidth: 52 }, 1: { cellWidth: 120 }, 3: { cellWidth: 82 }, 4: { cellWidth: 140 } });
    else section('Misconfigurations', f.misconfigs, ['Severity', 'ID', 'Title', 'File', 'How to fix'],
      (m) => [m.severity, clean(m.id), clean(m.title), clean(m.target), clean(m.resolution || m.message)], { 0: { cellWidth: 52 }, 1: { cellWidth: 62 }, 4: { cellWidth: 150 } });
    section('Licenses', f.licenses, ['Severity', 'Package', 'License', 'Category', 'Target'],
      (l) => [l.severity, clean(l.pkg), clean(l.name), clean(l.category), clean(l.target)], { 0: { cellWidth: 52 } });

    footers(doc, brand);
    return doc;
  };
  window.scanPdfName = (scan) => `vulnora-report_${fileSafe(scan.target)}_${new Date().toISOString().slice(0, 10)}.pdf`;
  window.buildPdfReport = async function (scan, brandOverride) {
    const doc = await window.createScanPdf(scan, brandOverride);
    doc.save(window.scanPdfName(scan));
  };

  /* ================= comparison report ================= */
  // cmp = { a, b, rows: [{status:'new'|'fixed'|'same', type, severity, id, item, info, target}], sevA, sevB, byType }
  window.buildComparePdf = async function (cmp) {
    const { jsPDF } = window.jspdf;
    const brand = await getBrand();
    const doc = new jsPDF({ unit: 'pt', format: 'a4' });
    const W = doc.internal.pageSize.getWidth(), M = 40;
    const HS = headStyles(brand);
    const { a, b, rows } = cmp;
    const nNew = rows.filter((r) => r.status === 'new').length, nFix = rows.filter((r) => r.status === 'fixed').length, nSame = rows.filter((r) => r.status === 'same').length;

    let y = await cover(doc, brand, {
      title: 'Scan Comparison Report',
      target: a.target === b.target ? b.target : `${a.target}  ->  ${b.target}`,
      metaLine: `Baseline ${new Date(a.createdAt).toLocaleString()}  |  Current ${new Date(b.createdAt).toLocaleString()}`,
    });

    doc.setTextColor(...INK); doc.setFont('helvetica', 'bold'); doc.setFontSize(14); doc.text('Summary', M, y);
    doc.setFont('helvetica', 'normal'); doc.setFontSize(10.5); doc.setTextColor(60, 64, 90);
    const net = total(cmp.sevB) - total(cmp.sevA);
    const verdict = nNew === 0 && nFix > 0 ? 'Improved: issues were fixed and nothing new was introduced.'
      : nNew > 0 && nFix === 0 ? 'Regressed: new issues were introduced and nothing was fixed.'
        : nNew === 0 && nFix === 0 ? 'No change between the two scans.'
          : net < 0 ? 'Mostly improved: more issues were fixed than introduced.' : 'Needs attention: more issues were introduced than fixed.';
    const newCrit = rows.filter((r) => r.status === 'new' && r.severity === 'CRITICAL').length;
    const txt = `${verdict} ${nFix} finding(s) fixed, ${nNew} new (${newCrit} critical), ${nSame} unchanged. Net change: ${net > 0 ? '+' : ''}${net}.`;
    const lines = doc.splitTextToSize(clean(txt), W - 2 * M);
    doc.text(lines, M, y + 18); y += 18 + lines.length * 13 + 8;

    // KPI tiles
    const tiles = [['NEW', nNew, [255, 61, 113]], ['FIXED', nFix, [52, 211, 153]], ['UNCHANGED', nSame, [139, 147, 167]], ['NET CHANGE', (net > 0 ? '+' : '') + net, net > 0 ? [255, 138, 61] : [56, 189, 248]]];
    const tw = (W - 2 * M - 3 * 8) / 4;
    tiles.forEach(([l, v, c], i) => {
      const x = M + i * (tw + 8);
      doc.setFillColor(...c); doc.roundedRect(x, y, tw, 52, 6, 6, 'F');
      doc.setTextColor(16, 18, 31); doc.setFont('helvetica', 'bold'); doc.setFontSize(20); doc.text(String(v), x + 12, y + 28);
      doc.setFontSize(8.5); doc.text(l, x + 12, y + 43);
    });
    y += 70;

    doc.autoTable({
      startY: y, margin: { left: M, right: M }, theme: 'grid',
      head: [['Severity', 'Baseline', 'Current', 'Change', 'New', 'Fixed']],
      body: SEVS.map((s) => { const d = (cmp.sevB[s] || 0) - (cmp.sevA[s] || 0); return [s, cmp.sevA[s] || 0, cmp.sevB[s] || 0, (d > 0 ? '+' : '') + d, rows.filter((r) => r.status === 'new' && r.severity === s).length, rows.filter((r) => r.status === 'fixed' && r.severity === s).length]; }),
      headStyles: HS, styles: { fontSize: 9.5, cellPadding: 5 }, didParseCell: sevCellAt(0),
    });
    y = doc.lastAutoTable.finalY + 14;
    doc.autoTable({
      startY: y, margin: { left: M, right: M }, theme: 'plain',
      body: [['Baseline', clean(`${a.target}  (${a.module}, ${new Date(a.createdAt).toLocaleString()}, scanners: ${(a.scanners || []).join(', ')})`)],
        ['Current', clean(`${b.target}  (${b.module}, ${new Date(b.createdAt).toLocaleString()}, scanners: ${(b.scanners || []).join(', ')})`)]].concat(brand.preparedBy ? [['Prepared by', clean(brand.preparedBy)]] : []),
      styles: { fontSize: 9, cellPadding: 3, textColor: [60, 64, 90] }, columnStyles: { 0: { fontStyle: 'bold', cellWidth: 80, textColor: INK } },
    });

    const section = (title, list) => {
      if (!list.length) return;
      const sorted = list.slice().sort((p, q) => RANK[p.severity] - RANK[q.severity]).slice(0, MAX_ROWS);
      doc.addPage();
      doc.setFont('helvetica', 'bold'); doc.setFontSize(15); doc.setTextColor(...INK); doc.text(`${title} (${list.length})`, M, M + 6);
      stripe(doc, M + 12, 2.5, 90, M);
      doc.autoTable({
        startY: M + 30, margin: { left: M, right: M, bottom: 36 }, theme: 'striped',
        head: [['Severity', 'Type', 'ID', 'Package / item', 'Details', 'Target']],
        body: sorted.map((r) => [r.severity, r.type, clean(r.id), clean(r.item), clean(r.info), clean(r.target)]),
        headStyles: { ...HS, fontSize: 8.5 }, styles: { fontSize: 7.8, cellPadding: 3.5, overflow: 'linebreak', valign: 'top' },
        columnStyles: { 0: { cellWidth: 52 }, 1: { cellWidth: 52 }, 2: { cellWidth: 80 } }, didParseCell: sevCellAt(0), rowPageBreak: 'avoid',
      });
    };
    section('New findings (introduced since baseline)', rows.filter((r) => r.status === 'new'));
    section('Fixed findings (no longer present)', rows.filter((r) => r.status === 'fixed'));

    footers(doc, brand);
    doc.save(`vulnora-compare_${fileSafe(b.target)}_${new Date().toISOString().slice(0, 10)}.pdf`);
  };
})();
